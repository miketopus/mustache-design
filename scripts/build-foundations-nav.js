#!/usr/bin/env node
/**
 * Generates js/foundations-nav.js from every foundations/*.html file's
 * <title> tag. This is the fix for having to hand-edit the sidebar (and
 * the overview tiles) every time a new Foundations page is published:
 * drop a .html file in foundations/ with the right <title>, and it shows
 * up on its own next time this runs.
 *
 * Order: "Overview" (foundation.html) always first, then every other page
 * alphabetically by its label — nobody curates position by hand anymore,
 * so there is nothing to forget.
 *
 * Usage:
 *   node scripts/build-foundations-nav.js            one-shot
 *   node scripts/build-foundations-nav.js --watch     regenerate on change
 */
'use strict';

const fs = require('fs');
const path = require('path');

const FOUNDATIONS_DIR = path.join(__dirname, '..', 'foundations');
const OUT_FILE = path.join(__dirname, '..', 'js', 'foundations-nav.js');
const TITLE_RE = /<title>\s*Design\s*·\s*(.+?)\s*—\s*Mustache Design System\s*<\/title>/i;

function titleCaseFromFilename(file) {
  return file
    .replace(/\.html$/, '')
    .split('-')
    .map(function (w) { return w.charAt(0).toUpperCase() + w.slice(1); })
    .join(' ');
}

function readLabel(file) {
  const html = fs.readFileSync(path.join(FOUNDATIONS_DIR, file), 'utf8');
  const m = html.match(TITLE_RE);
  if (m) return m[1].trim();
  console.warn(
    '[build-foundations-nav] ' + file + ' has no "<title>Design · X — Mustache ' +
    'Design System</title>" tag — falling back to a filename-derived label ("' +
    titleCaseFromFilename(file) + '"). Add that title to control the label shown in the sidebar.'
  );
  return titleCaseFromFilename(file);
}

function build() {
  const files = fs.readdirSync(FOUNDATIONS_DIR).filter(function (f) {
    return f.endsWith('.html') && f !== 'foundation.html';
  });

  const entries = files
    .map(function (file) { return { label: readLabel(file), href: file }; })
    .sort(function (a, b) { return a.label.localeCompare(b.label, 'es'); });

  entries.unshift({ label: 'Overview', href: 'foundation.html' });

  const body = entries.map(function (e) {
    return '  { label: ' + JSON.stringify(e.label) + ', href: ' + JSON.stringify(e.href) + ' }';
  }).join(',\n');

  const output =
    '/**\n' +
    ' * AUTO-GENERATED by scripts/build-foundations-nav.js — do not edit by hand,\n' +
    ' * your changes will be overwritten next time it runs (dev watcher or\n' +
    ' * `npm run build:nav`).\n' +
    ' *\n' +
    ' * Shared "Foundations" sidebar list, read by every foundations/*.html\n' +
    ' * page (and the overview tiles on foundations/foundation.html). Order:\n' +
    ' * Overview first, then alphabetical by label.\n' +
    ' *\n' +
    ' * To publish a new foundation page: add the .html file under\n' +
    ' * foundations/ with a `<title>Design · Your Label — Mustache Design\n' +
    ' * System</title>` tag. It appears in the sidebar and the overview grid\n' +
    ' * on its own — nothing else to touch.\n' +
    ' */\n' +
    'window.FOUNDATIONS_NAV = [\n' + body + '\n];\n';

  const prev = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, 'utf8') : null;
  if (prev !== output) {
    fs.writeFileSync(OUT_FILE, output);
    console.log('[build-foundations-nav] updated js/foundations-nav.js (' + entries.length + ' pages)');
  }
}

function watch() {
  build();
  let timer = null;
  fs.watch(FOUNDATIONS_DIR, function () {
    clearTimeout(timer);
    timer = setTimeout(build, 150);
  });
  console.log('[build-foundations-nav] watching foundations/ for changes…');
}

if (require.main === module) {
  if (process.argv.includes('--watch')) watch(); else build();
}

module.exports = { build: build, watch: watch };
